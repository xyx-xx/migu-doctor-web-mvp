def get_system_prompt(task):
    """task 已由请求校验层验证；缺失时仍拒绝而不是回退到通用提示词。"""
    try:
        return TASK_PROMPTS[task]
    except KeyError as exc:
        raise ValueError("没有为该 task 配置系统提示词") from exc
